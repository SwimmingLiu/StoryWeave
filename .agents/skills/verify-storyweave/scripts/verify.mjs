function childProof(proof, name) {
  return { ...proof, directory: join(proof.directory, name), work: join(proof.work, name), commands: [], actions: [], findings: [], traces: [], browser_errors: [], network_requests: [], entry_points: [], limitations: [] };
}

function mergeProof(proof, child) {
  const prefix = relative(proof.directory, child.directory);
  proof.commands.push(...child.commands);
  proof.actions.push(...child.actions.map((action) => ({ ...action, scope: prefix, ...(action.screenshot ? { screenshot: join(prefix, action.screenshot) } : {}) })));
  proof.traces.push(...child.traces.map((trace) => join(prefix, trace)));
  proof.entry_points.push(...child.entry_points.map((entry) => `${prefix}: ${entry}`));
  proof.findings.push(...child.findings);
  proof.browser_errors.push(...child.browser_errors);
  proof.network_requests.push(...child.network_requests);
}

