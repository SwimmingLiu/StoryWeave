async function drive() {
  const feature = args[1];
  assert(features.includes(feature), `Choose a feature: ${features.join(', ')}`);
  const state = await loadRun();
  assert(!state.run.cleaned_up, 'This run is already cleaned up; launch a new run ID');
  assert.equal((await sourceIdentity()).fingerprint, state.run.source.fingerprint, 'Sources changed since launch; use a new run ID');
  // Each drive owns fresh CLI/browser sessions, so health is rechecked before every feature.
  const ready = await doctor();
  const lockPath = join(state.work, '.drive-lock');
  const lock = await open(lockPath, 'wx');
  const evidence = join(state.evidence, feature);
  let proof;
  try {
    await mkdir(evidence);
    await save(join(evidence, 'doctor.json'), ready);
    const work = join(state.work, feature);
    await mkdir(work);
    proof = { feature, status: 'pass', directory: evidence, work, browser: state.run.browser, started_at: new Date().toISOString(), source_fingerprint: state.run.source.fingerprint, entry_points: [], commands: [], actions: [], findings: [], traces: [], browser_errors: [], network_requests: [], limitations: [] };
    const themeRef = flag('--theme-ref', 'editorial/paper-magazine');
    try {
      if (feature === 'html-authoring' || feature === 'html-playback') {
        await observeHtml(proof, await htmlProject(proof, themeRef), feature === 'html-playback');
        if (feature === 'html-authoring' && flag('--visual-baseline')) await driveHtmlVisual(proof, flag('--visual-baseline'));
        if (feature === 'html-authoring' && args.includes('--compatibility')) await driveHtmlCompatibility(proof);
      }
      if (feature === 'themes') await driveThemes(proof, themeRef);
      if (feature === 'imagegen') await driveImagegen(proof, themeRef);
      if (feature === 'bento') await driveBento(proof, themeRef);
      if (feature === 'design-library') await driveDesignLibrary(proof, themeRef);
      if (feature === 'reference-gallery') await driveReferenceGallery(proof, { repo, cache: flag('--reference-cache'), command, program, withBrowser });
      if (feature === 'distribution') await driveDistribution(proof, themeRef);
    } catch (error) {
      proof.status = error.code === 'browser.policy_blocked' || error.code === 'reference.cache_missing' ? 'not-run' : 'fail';
      if (proof.status === 'not-run') {
        proof.blocked = { code: error.code, route: error.route, reason: error.message };
        proof.limitations.push(error.message);
      }
      proof.error = error.stack ?? error.message;
    } finally {
      proof.finished_source_fingerprint = (await sourceIdentity()).fingerprint;
      if (proof.finished_source_fingerprint !== proof.source_fingerprint) {
        proof.status = 'fail';
        proof.findings.push({ code: 'source.changed', before: proof.source_fingerprint, after: proof.finished_source_fingerprint, message: 'Sources changed during this drive; launch a fresh run before accepting the result.' });
      }
      const project = join(work, 'project');
      if (await exists(project)) await cp(project, join(evidence, 'project'), { recursive: true });
      await contactSheet(evidence);
      await save(join(evidence, 'actions.json'), proof.actions);
      await save(join(evidence, 'commands.json'), proof.commands);
      proof.finished_at = new Date().toISOString();
      proof.artifacts = await artifactIndex(evidence);
      await save(join(evidence, 'summary.json'), proof);
      state.run.features[feature] = { status: proof.status, summary: relative(state.directory, join(evidence, 'summary.json')) };
      await save(join(state.directory, 'run.json'), state.run);
    }
  } finally {
    await lock.close();
    await rm(lockPath, { force: true });
  }
  // Partial or blocked runs must not return success to CI or an agent calling this helper.
  process.exitCode = proof.status === 'pass' ? 0 : proof.status === 'needs-images' ? 3 : proof.status === 'not-run' ? 4 : 1;
  return { feature, status: proof.status, evidence, error: proof.error, limitations: proof.limitations };
}

async function cleanup() {
  const state = await loadRun();
  if (await exists(state.work)) {
    assert((await realpath(state.work)) === state.work, 'Work directory must not be a symlink');
    assert(!(await exists(join(state.work, '.drive-lock'))), 'A drive is active; do not clean a shared active workspace');
    await rm(state.work, { recursive: true });
  }
  state.run.cleaned_up = true;
  state.run.cleaned_at = new Date().toISOString();
  await save(join(state.directory, 'run.json'), state.run);
  for (const feature of Object.values(state.run.features)) await access(join(state.directory, feature.summary));
  return { status: 'cleaned', work_exists: await exists(state.work), evidence: state.evidence };
}

async function report() {
  const state = await loadRun();
  const results = {};
  for (const feature of features) {
    const result = state.run.features[feature];
    if (!result) { results[feature] = { status: 'not-run' }; continue; }
    const summary = await json(join(state.directory, result.summary));
    for (const artifact of summary.artifacts) assert.equal(hash(await readFile(join(state.directory, 'evidence', feature, artifact.path))), artifact.sha256, `Evidence changed: ${artifact.path}`);
    results[feature] = { status: summary.status, entry_points: summary.entry_points, blocked: summary.blocked, artifact_count: summary.artifacts.length, summary: join(state.directory, result.summary) };
  }
  // Technical browser success used to hide visual regressions. Recompute the separately bound review on every report.
  const visualDirectory = join(state.evidence, 'visual-assessment');
  const hasVisual = await exists(join(visualDirectory, 'packet.json')) || await exists(join(visualDirectory, 'assessment.json')) || await exists(join(state.evidence, 'html-authoring/visual-review/packet.json'));
  const visual = hasVisual ? await readVisualAssessment(visualDirectory) : { status: 'not-run', release_ready: false, improvement_claim: false };
  const technicalComplete = Object.values(results).every((result) => result.status === 'pass');
  const output = { run_id: state.run.run_id, revision: state.run.source.revision, source_fingerprint: state.run.source.fingerprint, cleaned_up: state.run.cleaned_up, work_exists: await exists(state.work), evidence: state.evidence, features: results, visual_acceptance: { status: visual.status, release_ready: visual.release_ready, improvement_claim: visual.improvement_claim, origin: visual.origin, summary: visual.summary, regressions: visual.items?.filter(({ verdict }) => verdict === 'regressed').map(({ id, losses, user_vetoes }) => ({ id, losses, user_vetoes })), assessment: hasVisual ? join(visualDirectory, 'assessment.json') : null }, release_ready: technicalComplete && visual.release_ready };
  if (Object.values(results).some((result) => result.status === 'fail') || visual.status === 'regressed') process.exitCode = 1;
  // A report with unvisited features previously exited zero despite incomplete coverage.
  else if (Object.values(results).some((result) => result.status === 'not-run')) process.exitCode = 4;
  else if (hasVisual && visual.status === 'needs-review') process.exitCode = 4;
  else if (Object.values(results).some((result) => result.status === 'needs-images')) process.exitCode = 3;
  return output;
}

